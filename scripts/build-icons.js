#!/usr/bin/env node
/**
 * Bizdavar icon pipeline — assets/icons/ui/*.svg is the single source of truth.
 *
 * Source grammar (24×24, root carries the navy 1.75 stroke):
 *   bare element   → stroked line art (currentColor at runtime)
 *   class="a"      → yellow accent
 *   class="r"      → red accent
 *   class="f"      → solid ink (currentColor at runtime)
 *
 * Outputs:
 *   assets/scripts/components/biz-icons.js   ICONS map (between @icons markers)
 *   assets/icons/categories/*.svg            240×240 catalogue tiles
 *   assets/styles/icons.css                  CSS mask / background vars (between @icons markers)
 *   assets/icons/sprite.svg                  <symbol> sprite for static HTML
 *   scripts/icon-preview.html                local gallery (not deployed)
 *
 * Run: npm run icons  (then npm run css)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const UI_DIR = path.join(ROOT, 'assets/icons/ui');
const CAT_DIR = path.join(ROOT, 'assets/icons/categories');
const BIZ_ICONS = path.join(ROOT, 'assets/scripts/components/biz-icons.js');
const ICONS_CSS = path.join(ROOT, 'assets/styles/icons.css');
const SPRITE = path.join(ROOT, 'assets/icons/sprite.svg');
const PREVIEW = path.join(ROOT, 'scripts/icon-preview.html');

const NAVY = '#1d1d1b';
const YELLOW = '#FFDE00';
const RED = '#E62833';
const CREAM = '#f4f0ea';

/* Catalogue tiles: tile file name → ui icon */
const TILES = {
  'car-air-filter': 'air-filter',
  'car-brake-pad': 'brake-pad',
  'car-emblem': 'emblem',
  'car-hood-emblem': 'hood-emblem',
  'car-oil-filter': 'oil-filter',
  'car-rim': 'rim',
  'motorcycle-accessory': 'tag',
  'motorcycle-boots': 'boots',
  'motorcycle-gloves': 'gloves',
  'motorcycle-helmet': 'helmet',
  'motorcycle-intercom': 'intercom',
  'motorcycle-jacket': 'jacket',
  'motorcycle-offroad': 'motorcycle',
  'motorcycle-pants': 'pants',
  'motorcycle-parts': 'sprocket',
  'motorcycle-protection': 'protection'
};

/* CSS vars: masks are single-colour (tinted via background-color), images keep their colour */
const CSS_VARS = [
  { v: '--bd-icon-check', icon: 'check', stroke: '#000', width: 2.5, accents: false },
  { v: '--bd-icon-arrow', icon: 'arrow-right', stroke: '#000', width: 2, accents: false },
  { v: '--bd-icon-arrow-rtl', icon: 'arrow-left', stroke: '#000', width: 2, accents: false },
  { v: '--bd-icon-star', icon: 'star', stroke: '#000', solid: true, accents: false },
  { v: '--bd-img-check-yellow', icon: 'check', stroke: YELLOW, width: 2.5, accents: false },
  { v: '--bd-img-image', icon: 'image', stroke: '#16163f', width: 1.5, accents: false },
  { v: '--bd-img-whatsapp-white', icon: 'whatsapp', stroke: '#fff', accents: false }
];

const ALIASES = { 'whatsapp-solid': 'whatsapp', 'chat-wa': 'whatsapp' };

function readIcons() {
  const icons = {};
  for (const file of fs.readdirSync(UI_DIR).filter((f) => f.endsWith('.svg')).sort()) {
    const name = file.slice(0, -4);
    if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`Bad icon name: ${file}`);
    const src = fs.readFileSync(path.join(UI_DIR, file), 'utf8');
    const m = src.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
    if (!m) throw new Error(`Not an svg: ${file}`);
    const elements = m[1].split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    icons[name] = elements;
  }
  return icons;
}

const ROLE_ATTRS = {
  a: / class="a" fill="#FFDE00" stroke="none"/,
  r: / class="r" fill="#E62833" stroke="none"/,
  f: / class="f" fill="#1d1d1b" stroke="none"/
};

function roleOf(el) {
  for (const [role, re] of Object.entries(ROLE_ATTRS)) if (re.test(el)) return role;
  if (/ class="/.test(el)) throw new Error(`Unknown class in: ${el}`);
  return 'line';
}

/* Re-paint each element for a target; map(role) returns attribute string or null to drop */
function paint(elements, map) {
  const out = [];
  for (const el of elements) {
    const role = roleOf(el);
    const attrs = map(role);
    if (attrs === null) continue;
    const bare = role === 'line' ? el : el.replace(ROLE_ATTRS[role], '');
    out.push(attrs ? bare.replace(/^<(\w+)/, `<$1 ${attrs}`) : bare);
  }
  return out.join('');
}

/* ── biz-icons.js ── */
function buildBizIcons(icons) {
  const lines = Object.entries(icons).map(([name, els]) => {
    const body = paint(els, (role) => ({
      line: '',
      a: '${A}',
      r: '${R}',
      f: '${F}'
    }[role]));
    const hasLine = els.some((el) => roleOf(el) === 'line');
    const markup = hasLine ? `<g \${S}>${body}</g>` : body;
    const key = /^[a-z]+$/.test(name) ? name : `'${name}'`;
    return `    ${key}: \`${markup}\``;
  });
  const aliases = Object.entries(ALIASES)
    .map(([alias, target]) => `  ICONS['${alias}'] = ICONS['${target}'];`).join('\n');
  const block = [
    '  /* @icons:start — generated by scripts/build-icons.js from assets/icons/ui/*.svg; do not edit */',
    '  const ICONS = {',
    lines.join(',\n'),
    '  };',
    aliases,
    '  /* @icons:end */'
  ].join('\n');

  let src = fs.readFileSync(BIZ_ICONS, 'utf8').replace(/\r\n/g, '\n');
  const start = src.indexOf('  /* @icons:start');
  const endMarker = '  /* @icons:end */';
  if (start !== -1) {
    const end = src.indexOf(endMarker, start) + endMarker.length;
    src = src.slice(0, start) + block + src.slice(end);
  } else {
    /* first run: replace the hand-written WhatsApp constants + ICONS map */
    const from = src.indexOf('  /* WhatsApp');
    const to = src.indexOf('\n\n  function resolveIconName');
    if (from === -1 || to === -1) throw new Error('biz-icons.js: cannot locate ICONS block');
    src = src.slice(0, from) + block + src.slice(to);
  }
  if (!src.includes("const F = ")) {
    src = src.replace(/(  const R = [^\n]+\n)/, `$1  const F = 'fill="currentColor" stroke="none"';\n`);
  }
  fs.writeFileSync(BIZ_ICONS, src);
}

/* ── standalone svg helpers ── */
function standalone(els, { stroke = NAVY, width = 1.75, accent = YELLOW, red = RED, ink = NAVY, solid = false, accents = true } = {}) {
  const body = paint(els, (role) => {
    if (role === 'line') return solid ? `fill="${stroke}"` : '';
    if (!accents && (role === 'a' || role === 'r')) return null;
    if (role === 'a') return `fill="${accent}" stroke="none"`;
    if (role === 'r') return `fill="${red}" stroke="none"`;
    return `fill="${role === 'f' && !accents ? stroke : ink}" stroke="none"`;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${stroke}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

function dataUri(svg) {
  return 'data:image/svg+xml,' + svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E');
}

/* ── category tiles ── */
function buildTiles(icons) {
  fs.mkdirSync(CAT_DIR, { recursive: true });
  for (const [tile, icon] of Object.entries(TILES)) {
    const els = icons[icon];
    if (!els) throw new Error(`Tile ${tile}: missing icon ${icon}`);
    const body = paint(els, (role) => ({
      line: '',
      a: `fill="${RED}" stroke="none"`,
      r: `fill="${RED}" stroke="none"`,
      f: `fill="${NAVY}" stroke="none"`
    }[role]));
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240" role="img" aria-label="${tile}">
  <rect width="240" height="240" rx="28" fill="${CREAM}"/>
  <circle cx="120" cy="120" r="84" fill="#fff"/>
  <g transform="translate(66 66) scale(4.5)" fill="none" stroke="${NAVY}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">${body}</g>
</svg>
`;
    fs.writeFileSync(path.join(CAT_DIR, `${tile}.svg`), svg);
  }
}

/* ── icons.css vars ── */
function buildCssVars(icons) {
  const decls = CSS_VARS.map(({ v, icon, ...opts }) => {
    if (!icons[icon]) throw new Error(`CSS var ${v}: missing icon ${icon}`);
    return `  ${v}: url("${dataUri(standalone(icons[icon], opts))}");`;
  }).join('\n');
  const block = `  /* @icons:start — generated by scripts/build-icons.js; do not edit */\n${decls}\n  /* @icons:end */`;
  let css = fs.readFileSync(ICONS_CSS, 'utf8').replace(/\r\n/g, '\n');
  const start = css.indexOf('  /* @icons:start');
  if (start !== -1) {
    const endMarker = '  /* @icons:end */';
    const end = css.indexOf(endMarker, start) + endMarker.length;
    css = css.slice(0, start) + block + css.slice(end);
  } else {
    css = css.replace(/(:root \{\n)(?:  --bd-icon-[^\n]+\n)+/, `$1${block}\n`);
    if (!css.includes('@icons:start')) throw new Error('icons.css: cannot locate :root vars');
  }
  fs.writeFileSync(ICONS_CSS, css);
}

/* ── sprite ── */
function buildSprite(icons) {
  const symbols = Object.entries(icons).map(([name, els]) => {
    const body = paint(els, (role) => ({
      line: '',
      a: `fill="var(--yellow,${YELLOW})" stroke="none"`,
      r: `fill="var(--red,${RED})" stroke="none"`,
      f: 'fill="currentColor" stroke="none"'
    }[role]));
    return `  <symbol id="bd-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`;
  });
  fs.writeFileSync(SPRITE, `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join('\n')}\n</svg>\n`);
}

/* ── preview gallery ── */
function buildPreview(icons) {
  const cards = Object.keys(icons).map((name) =>
    `<figure><img src="../assets/icons/ui/${name}.svg" width="40" height="40" alt=""><figcaption>${name}</figcaption></figure>`
  ).join('\n');
  const tiles = Object.keys(TILES).map((t) =>
    `<figure><img src="../assets/icons/categories/${t}.svg" width="120" height="120" alt=""><figcaption>${t}</figcaption></figure>`
  ).join('\n');
  fs.writeFileSync(PREVIEW, `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Bizdavar icons (${Object.keys(icons).length})</title>
<style>
body{font-family:system-ui,sans-serif;margin:32px;background:#fafaf7;color:${NAVY}}
h1{font-size:20px}h2{font-size:15px;margin-top:32px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(104px,1fr));gap:10px}
figure{margin:0;padding:14px 6px;background:#fff;border:1px solid #ebe8e1;border-radius:12px;text-align:center}
figcaption{font-size:11px;margin-top:8px;color:#555;word-break:break-all}
.tiles{grid-template-columns:repeat(auto-fill,minmax(150px,1fr))}
</style></head><body>
<h1>Bizdavar icon set — ${Object.keys(icons).length} icons</h1>
<div class="grid">
${cards}
</div>
<h2>Catalogue tiles</h2>
<div class="grid tiles">
${tiles}
</div>
</body></html>
`);
}

const icons = readIcons();
buildBizIcons(icons);
buildTiles(icons);
buildCssVars(icons);
buildSprite(icons);
buildPreview(icons);
console.log(`Icons: ${Object.keys(icons).length} → biz-icons.js, sprite.svg, ${Object.keys(TILES).length} tiles, ${CSS_VARS.length} css vars, preview`);
